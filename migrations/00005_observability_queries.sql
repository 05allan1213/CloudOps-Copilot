  CONSTRAINT `fk_query_executions_definition` FOREIGN KEY (`query_definition_id`) REFERENCES `query_definitions` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_query_executions_authorization` FOREIGN KEY (`query_authorization_id`) REFERENCES `query_authorizations` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `chk_query_executions_actor` CHECK ((`actor` in (_ascii'owner',_ascii'agent'))),
  CONSTRAINT `chk_query_executions_provider` CHECK ((`provider` = _ascii'prometheus')),
  CONSTRAINT `chk_query_executions_mode` CHECK ((`mode` in (_ascii'guided',_ascii'expert'))),
  CONSTRAINT `chk_query_executions_status` CHECK ((`status` in (_ascii'pending',_ascii'running',_ascii'succeeded',_ascii'failed',_ascii'cancelled'))),
  CONSTRAINT `chk_query_executions_range` CHECK ((`range_end` > `range_start` AND `step_seconds` > 0)),
  CONSTRAINT `chk_query_executions_bounds` CHECK ((`timeout_ms` > 0 AND `max_response_bytes` > 0 AND `max_series` > 0 AND `max_samples` > 0 AND `concurrency_limit` > 0)),
  CONSTRAINT `chk_query_executions_hash` CHECK ((char_length(`query_hash`) = 64)),
  CONSTRAINT `chk_query_executions_namespaces` CHECK ((json_type(`namespaces_json`) = _utf8mb4'ARRAY' AND json_length(`namespaces_json`) between 1 and 100)),
  CONSTRAINT `chk_query_executions_terminal` CHECK (((`status` in (_ascii'pending',_ascii'running') AND `completed_at` is null) OR (`status` in (_ascii'succeeded',_ascii'failed',_ascii'cancelled') AND `completed_at` is not null)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

