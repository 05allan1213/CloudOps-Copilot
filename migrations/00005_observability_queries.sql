  CONSTRAINT `chk_query_definitions_provider` CHECK ((`provider` = _ascii'prometheus')),
  CONSTRAINT `chk_query_definitions_bounds` CHECK ((`max_lookback_seconds` > 0 AND `max_series` > 0 AND `max_samples` > 0)),
  CONSTRAINT `chk_query_definitions_namespaces` CHECK ((json_type(`namespaces_json`) = _utf8mb4'ARRAY' AND json_length(`namespaces_json`) between 1 and 100))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

